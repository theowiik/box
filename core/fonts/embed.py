"""Regenerate src/fonts.inc from the subset fonts in this folder.

The fonts are Inter 4.1 (SIL Open Font License, see LICENSE-Inter.txt),
subset to Latin-1 plus common punctuation so they fit in flash:

    uv run --with fonttools pyftsubset Inter-Bold.ttf \\
        --unicodes="U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+20AC,U+2190-2193" \\
        --layout-features=kern --no-hinting --desubroutinize --output-file=Inter-Bold-latin.ttf

Run from anywhere: python core/fonts/embed.py
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
FONTS = {"box_font_bold": "Inter-Bold-latin.ttf", "box_font_medium": "Inter-Medium-latin.ttf"}

out = ["/* Generated by core/fonts/embed.py from the subset Inter fonts. Do not edit. */"]
for name, file in FONTS.items():
    data = (HERE / file).read_bytes()
    out.append(f"static const unsigned char {name}[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    out.append("};")
(HERE.parent / "src" / "fonts.inc").write_text("\n".join(out) + "\n")
print("wrote src/fonts.inc")
